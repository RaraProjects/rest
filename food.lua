Food = T{}

Food.Name = "Unknown"
Food.HHP_Value = 0
Food.HMP_Value = 0

-- ------------------------------------------------------------------------------------------------------
-- Calculates additional HMP from food.
-- ------------------------------------------------------------------------------------------------------
---@return table
-- ------------------------------------------------------------------------------------------------------
Food.HPMP = function()
    local has_food = Ashita.Has_Food()
    if not has_food then
        Food.HHP_Value = 0
        Food.HMP_Value = 0
    end
    return {hhp = Food.HHP_Value, hmp = Food.HMP_Value}
end

-- ------------------------------------------------------------------------------------------------------
-- Gets the name for the HMP food.
-- ------------------------------------------------------------------------------------------------------
---@return string
-- ------------------------------------------------------------------------------------------------------
Food.Get_Name = function()
    local has_food = Ashita.Has_Food()
    if not has_food then Food.Name = "No Food" end
    return Food.Name
end

-- ------------------------------------------------------------------------------------------------------
-- Sets food HMP value.
-- ------------------------------------------------------------------------------------------------------
---@param hmp integer
-- ------------------------------------------------------------------------------------------------------
Food.Set_HMP = function(hmp)
    if not hmp then return nil end
    Food.HMP_Value = hmp
end

-- ------------------------------------------------------------------------------------------------------
-- Sets food name value.
-- ------------------------------------------------------------------------------------------------------
---@param name string
-- ------------------------------------------------------------------------------------------------------
Food.Set_Name = function(name)
    if not name then return nil end
    Food.Name = name
end